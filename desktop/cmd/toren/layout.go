package main

// toren layout: a layout per workspace.
//
// Hyprland (0.54+) takes a tiling algorithm per workspace from a workspace
// rule: dwindle, master, monocle or scrolling. Floating is not an algorithm:
// a window rule floats every new window on the workspace, and the windows
// already there are floated on the switch.
//
// The choice is kept in ~/.config/toren/layouts.json and rendered as
// ~/.config/toren/hyprland/layouts.lua, which hyprland.lua sources, so it
// holds across logins. A workspace with no entry follows the default tiling
// layout (Settings -> Window Manager -> Layout). On a change Hyprland reloads
// its config, so the rules are rebuilt from the files, and the windows on the
// workspace are floated (or tiled again) to match.

import (
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"time"

	"toren/desktop/internal/runner"
)

func init() {
	register("layout", "the current workspace's layout: tile, scroll, master, monocle or float", torenLayout)
}

const layoutUsage = `Usage: toren layout [status]
       toren layout set tile|scroll|master|monocle|float|default [--workspace ID]
       toren layout next|prev [--workspace ID]

Each workspace has its own layout. A workspace without one follows the default
tiling layout (Settings -> Window Manager -> Layout).

  tile     windows split the screen (dwindle)
  scroll   windows sit in a row wider than the screen; scroll through them
  master   one large window and a stack beside it
  monocle  one window fills the screen at a time
  float    windows float freely and overlap
  default  drop this workspace's choice
`

// layoutOrder is the cycle order for next/prev.
var layoutOrder = []string{"tile", "scroll", "master", "monocle", "float"}

// hyprAlgo maps a layout to Hyprland's tiling algorithm ("" for float).
var hyprAlgo = map[string]string{
	"tile": "dwindle", "scroll": "scrolling", "master": "master", "monocle": "monocle", "float": "",
}

var layoutLabel = map[string]string{
	"tile": "Tiling", "scroll": "Scrolling", "master": "Master", "monocle": "Monocle", "float": "Floating",
}

// layoutState is layouts.json: workspace ID -> layout name.
type layoutState struct {
	Workspaces map[string]string `json:"workspaces"`
}

func layoutConfigHome() string {
	if d := os.Getenv("XDG_CONFIG_HOME"); d != "" {
		return d
	}
	home, _ := os.UserHomeDir()
	return filepath.Join(home, ".config")
}

func layoutStatePath() string { return filepath.Join(layoutConfigHome(), "toren", "layouts.json") }
func layoutLuaPath() string {
	return filepath.Join(layoutConfigHome(), "toren", "hyprland", "layouts.lua")
}

// layoutFloatedPath lists the windows `toren layout` floated, so leaving float
// tiles exactly those and leaves dialogs the apps float themselves alone.
func layoutFloatedPath() string {
	dir := os.Getenv("XDG_RUNTIME_DIR")
	if dir == "" {
		dir = os.TempDir()
	}
	return filepath.Join(dir, "toren-layout-floated.json")
}

func loadLayoutState(path string) layoutState {
	st := layoutState{Workspaces: map[string]string{}}
	b, err := os.ReadFile(path)
	if err != nil {
		return st
	}
	_ = json.Unmarshal(b, &st)
	if st.Workspaces == nil {
		st.Workspaces = map[string]string{}
	}
	for ws, l := range st.Workspaces {
		if _, ok := hyprAlgo[l]; !ok {
			delete(st.Workspaces, ws)
		}
	}
	return st
}

func writeFileAtomic(path string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

func saveLayoutState(path string, st layoutState) error {
	b, err := json.MarshalIndent(st, "", "  ")
	if err != nil {
		return err
	}
	return writeFileAtomic(path, append(b, '\n'))
}

// workspaceKeys sorts workspace IDs numerically, names after numbers.
func workspaceKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool {
		a, errA := strconv.Atoi(keys[i])
		b, errB := strconv.Atoi(keys[j])
		switch {
		case errA == nil && errB == nil:
			return a < b
		case errA == nil:
			return true
		case errB == nil:
			return false
		}
		return keys[i] < keys[j]
	})
	return keys
}

// luaString quotes a value for a Lua string literal.
func luaString(s string) string { return strconv.Quote(s) }

// renderLayoutLua is layouts.lua for a state.
func renderLayoutLua(st layoutState) string {
	var b strings.Builder
	b.WriteString("-- Generated by toren layout. Do not edit: `toren layout` rewrites it.\n")
	b.WriteString("-- One layout per workspace; the rest follow the default tiling layout.\n")
	for _, ws := range workspaceKeys(st.Workspaces) {
		l := st.Workspaces[ws]
		if algo := hyprAlgo[l]; algo != "" {
			fmt.Fprintf(&b, "hl.workspace_rule({ workspace = %s, layout = %s })\n", luaString(ws), luaString(algo))
		} else {
			fmt.Fprintf(&b, "hl.window_rule({ name = %s, match = { workspace = %s }, float = true })\n",
				luaString("toren-layout-float-"+ws), luaString(ws))
		}
	}
	return b.String()
}

// nextLayout steps through layoutOrder from the current one.
func nextLayout(current string, step int) string {
	i := 0
	for k, l := range layoutOrder {
		if l == current {
			i = k
			break
		}
	}
	n := len(layoutOrder)
	return layoutOrder[((i+step)%n+n)%n]
}

type hyprWorkspace struct {
	ID   int    `json:"id"`
	Name string `json:"name"`
}

type hyprClient struct {
	Address   string        `json:"address"`
	Floating  bool          `json:"floating"`
	Workspace hyprWorkspace `json:"workspace"`
}

func activeWorkspaceID(run runner.Func) (string, error) {
	out, err := run("hyprctl", "-j", "activeworkspace")
	if err != nil {
		return "", fmt.Errorf("cannot ask Hyprland for the current workspace: %s", runner.Reason(err))
	}
	var ws hyprWorkspace
	if err := json.Unmarshal([]byte(out), &ws); err != nil || ws.ID == 0 {
		return "", errors.New("cannot read the current workspace from Hyprland")
	}
	return strconv.Itoa(ws.ID), nil
}

// defaultTiling is Hyprland's general:layout, for status output.
func defaultTiling(run runner.Func) string {
	out, err := run("hyprctl", "-j", "getoption", "general:layout")
	if err != nil {
		return "dwindle"
	}
	var opt struct {
		Str string `json:"str"`
	}
	if json.Unmarshal([]byte(out), &opt) != nil || opt.Str == "" {
		return "dwindle"
	}
	return opt.Str
}

func torenLayout(args []string) int {
	return layoutMain(args, os.Stdout, os.Stderr, runner.Exec(10*time.Second))
}

func layoutMain(args []string, out, errOut io.Writer, run runner.Func) int {
	verb := "status"
	if len(args) > 0 {
		verb = args[0]
		args = args[1:]
	}
	if verb == "-h" || verb == "--help" || verb == "help" {
		fmt.Fprint(out, layoutUsage)
		return exitOK
	}

	ws := ""
	var rest []string
	for i := 0; i < len(args); i++ {
		switch {
		case args[i] == "--workspace" && i+1 < len(args):
			ws = args[i+1]
			i++
		case strings.HasPrefix(args[i], "--workspace="):
			ws = strings.TrimPrefix(args[i], "--workspace=")
		default:
			rest = append(rest, args[i])
		}
	}

	st := loadLayoutState(layoutStatePath())

	if ws == "" {
		id, err := activeWorkspaceID(run)
		if err != nil {
			if verb == "status" {
				// outside a session: list what is stored
				for _, k := range workspaceKeys(st.Workspaces) {
					fmt.Fprintf(out, "workspace %s: %s\n", k, st.Workspaces[k])
				}
				return exitOK
			}
			fmt.Fprintln(errOut, "toren layout:", err)
			return exitFail
		}
		ws = id
	}

	current, own := st.Workspaces[ws]
	switch verb {
	case "status":
		if own {
			fmt.Fprintf(out, "workspace %s: %s\n", ws, current)
		} else {
			fmt.Fprintf(out, "workspace %s: default (%s)\n", ws, defaultTiling(run))
		}
		return exitOK
	case "next", "prev":
		step := 1
		if verb == "prev" {
			step = -1
		}
		if !own {
			// from the default tiling layout, step relative to "tile"
			current = "tile"
		}
		return applyLayout(ws, nextLayout(current, step), st, out, errOut, run)
	case "set":
		if len(rest) != 1 {
			fmt.Fprint(errOut, layoutUsage)
			return exitUsage
		}
		want := rest[0]
		if _, ok := hyprAlgo[want]; !ok && want != "default" {
			fmt.Fprintf(errOut, "toren layout: unknown layout %q (tile, scroll, master, monocle, float or default)\n", want)
			return exitUsage
		}
		return applyLayout(ws, want, st, out, errOut, run)
	}
	fmt.Fprint(errOut, layoutUsage)
	return exitUsage
}

func applyLayout(ws, want string, st layoutState, out, errOut io.Writer, run runner.Func) int {
	was := st.Workspaces[ws]
	if want == "default" {
		delete(st.Workspaces, ws)
	} else {
		st.Workspaces[ws] = want
	}
	if err := saveLayoutState(layoutStatePath(), st); err != nil {
		fmt.Fprintln(errOut, "toren layout:", err)
		return exitFail
	}
	if err := writeFileAtomic(layoutLuaPath(), []byte(renderLayoutLua(st))); err != nil {
		fmt.Fprintln(errOut, "toren layout:", err)
		return exitFail
	}

	// Rebuild the rules from the files, then let Hyprland recompute every
	// workspace's tiling algorithm (-r refreshes the layouts).
	if _, err := run("hyprctl", "reload"); err != nil {
		fmt.Fprintln(errOut, "toren layout: saved; Hyprland did not reload:", runner.Reason(err))
		return exitFail
	}
	_, _ = run("hyprctl", "-r", "eval", "return true")

	switch {
	case want == "float" && was != "float":
		floatWorkspace(ws, run)
	case was == "float" && want != "float":
		unfloatWorkspace(ws, run)
	}

	label := "Default"
	if want != "default" {
		label = layoutLabel[want]
	}
	fmt.Fprintf(out, "workspace %s: %s\n", ws, strings.ToLower(label))
	// one notification that updates in place
	_, _ = run("notify-send", "-a", "Toren", "-r", "47213", "-t", "1500", "-i", "view-grid-symbolic",
		"Workspace "+ws+": "+label+" layout")
	return exitOK
}

func workspaceClients(ws string, run runner.Func) []hyprClient {
	outp, err := run("hyprctl", "-j", "clients")
	if err != nil {
		return nil
	}
	var all []hyprClient
	if json.Unmarshal([]byte(outp), &all) != nil {
		return nil
	}
	var on []hyprClient
	for _, c := range all {
		if strconv.Itoa(c.Workspace.ID) == ws {
			on = append(on, c)
		}
	}
	return on
}

func floatWindow(addr, action string, run runner.Func) {
	_, _ = run("hyprctl", "dispatch",
		fmt.Sprintf("hl.dsp.window.float({ action = %s, window = %s })", luaString(action), luaString("address:"+addr)))
}

// floatWorkspace floats the workspace's tiled windows and remembers them.
func floatWorkspace(ws string, run runner.Func) {
	floated := loadFloated()
	for _, c := range workspaceClients(ws, run) {
		if c.Floating {
			continue
		}
		floatWindow(c.Address, "enable", run)
		floated[ws] = append(floated[ws], c.Address)
	}
	saveFloated(floated)
}

// unfloatWorkspace tiles again the windows floatWorkspace floated.
func unfloatWorkspace(ws string, run runner.Func) {
	floated := loadFloated()
	mine := map[string]bool{}
	for _, a := range floated[ws] {
		mine[a] = true
	}
	for _, c := range workspaceClients(ws, run) {
		if c.Floating && mine[c.Address] {
			floatWindow(c.Address, "disable", run)
		}
	}
	delete(floated, ws)
	saveFloated(floated)
}

func loadFloated() map[string][]string {
	m := map[string][]string{}
	if b, err := os.ReadFile(layoutFloatedPath()); err == nil {
		_ = json.Unmarshal(b, &m)
	}
	return m
}

func saveFloated(m map[string][]string) {
	if b, err := json.Marshal(m); err == nil {
		_ = writeFileAtomic(layoutFloatedPath(), b)
	}
}
